/**
 * Generates `app/content/courses/meta.ts` and `app/content/projects/meta.ts`.
 *
 * The metadata (slugs, titles, objectives, exercise counts, quizzes, project
 * summaries) is what every catalogue page, the sidebar, search and stats need,
 * so it is bundled eagerly. Lesson bodies, project briefs and starter files
 * stay inside their own modules. Section bodies load through the generated
 * `section-loaders.ts`; full projects load through `projects/load.ts`.
 *
 * Regenerate with: npm run generate:course-meta
 */
import { writeFileSync } from 'node:fs'
import { cssFundamentals } from '../app/content/courses/css-fundamentals'
import { htmlFundamentals } from '../app/content/courses/html-fundamentals'
import { javascriptFundamentals } from '../app/content/courses/javascript-fundamentals'
import { domBrowserApisCourse } from '../app/content/courses/dom-browser-apis-course'
import { responsiveWebDesignCourse } from '../app/content/courses/responsive-web-design-course'
import { gitGitHubCourse } from '../app/content/courses/git-github-course'
import { typescriptFundamentals } from '../app/content/courses/typescript-fundamentals'
import { reactCourse } from '../app/content/courses/react'
import { frontendProjectsCourse } from '../app/content/courses/frontend-projects-course'
import { coreProjects } from '../app/content/projects/core'
import { htmlProjects } from '../app/content/projects/html'
import { cssProjects } from '../app/content/projects/css'
import { javascriptProjects } from '../app/content/projects/javascript'
import { typescriptProjects } from '../app/content/projects/typescript'
import { reactProjects } from '../app/content/projects/react'
import type {
  Course,
  CourseMeta,
  Project,
  ProjectGroup,
  ProjectSummary,
} from '../app/types/content'

function toMeta(course: Course): CourseMeta {
  return {
    id: course.id,
    slug: course.slug,
    title: course.title,
    shortTitle: course.shortTitle,
    description: course.description,
    technology: course.technology,
    category: course.category,
    type: course.type,
    difficulty: course.difficulty,
    badges: course.badges,
    topics: course.topics,
    icon: course.icon,
    projects: course.projects.map((project) => project.slug),
    sections: course.sections.map((section) => ({
      id: section.id,
      title: section.title,
      description: section.description,
      lessons: section.lessons.map((lesson) => ({
        id: lesson.id,
        title: lesson.title,
        description: lesson.description,
        duration: lesson.duration,
        objectives: lesson.objectives,
        xp: lesson.xp,
        exerciseCount: lesson.content.filter((block) => block.type === 'exercise').length,
        quiz: {
          id: lesson.quiz.id,
          title: lesson.quiz.title,
          passingScore: lesson.quiz.passingScore,
          questionCount: lesson.quiz.questions.length,
        },
      })),
      chapter: section.chapter,
    })),
  }
}

const courseMeta: CourseMeta[] = [
  htmlFundamentals,
  cssFundamentals,
  javascriptFundamentals,
  domBrowserApisCourse,
  responsiveWebDesignCourse,
  gitGitHubCourse,
  typescriptFundamentals,
  reactCourse,
  frontendProjectsCourse,
].map(toMeta)

const projectGroups: Record<ProjectGroup, Project[]> = {
  core: coreProjects,
  html: htmlProjects,
  css: cssProjects,
  javascript: javascriptProjects,
  typescript: typescriptProjects,
  react: reactProjects,
}

function toSummary(project: Project, group: ProjectGroup): ProjectSummary {
  return {
    id: project.id,
    slug: project.slug,
    title: project.title,
    tagline: project.tagline,
    summary: project.summary,
    difficulty: project.difficulty,
    technologies: project.technologies,
    estimatedMinutes: project.estimatedMinutes,
    xp: project.xp,
    checklistCount: project.checklist.length,
    group,
  }
}

const projectSummaries: ProjectSummary[] = Object.entries(projectGroups).flatMap(
  ([group, projects]) =>
    projects.map((project) => toSummary(project, group as ProjectGroup)),
)

const output = `// Generated by scripts/generate-course-meta.ts — edit the course modules and
// run \`npm run generate:course-meta\` instead of editing this file.
import type { CourseMeta } from '~/types/content'

export const courseMeta: CourseMeta[] = ${JSON.stringify(courseMeta, null, 2)}
`

const projectOutput = `// Generated by scripts/generate-course-meta.ts - edit the project modules and
// run \`npm run generate:course-meta\` instead of editing this file.
import type { ProjectSummary } from '~/types/content'

export const projectSummaries: ProjectSummary[] = ${JSON.stringify(projectSummaries, null, 2)}
`

writeFileSync(new URL('../app/content/courses/meta.ts', import.meta.url), output)
writeFileSync(new URL('../app/content/projects/meta.ts', import.meta.url), projectOutput)
console.log(
  `Wrote course meta for ${courseMeta.length} courses and ${projectSummaries.length} projects`,
)
