/**
 * Generates `app/content/courses/meta.ts` from the course modules.
 *
 * The metadata (slugs, titles, objectives, exercise counts, quizzes) is
 * what every catalogue page, the sidebar, search and stats need, so it is
 * bundled eagerly. Lesson bodies, examples and exercises stay inside the
 * per-course modules, which `loadCourse` imports on demand.
 *
 * Regenerate with: npm run generate:course-meta
 */
import { writeFileSync } from 'node:fs'
import { cssFundamentals } from '../app/content/courses/css-fundamentals'
import { htmlFundamentals } from '../app/content/courses/html-fundamentals'
import { javascriptFundamentals } from '../app/content/courses/javascript-fundamentals'
import { domBrowserApisCourse } from '../app/content/courses/dom-browser-apis-course'
import { responsiveWebDesignCourse } from '../app/content/courses/responsive-web-design-course'
import { gitGitHubCourse } from '../app/content/courses/git-github-course'
import { typescriptFundamentals } from '../app/content/courses/typescript-fundamentals'
import { reactCourse } from '../app/content/courses/react'
import { frontendProjectsCourse } from '../app/content/courses/frontend-projects-course'
import type { Course, CourseMeta } from '../app/types/content'

function toMeta(course: Course): CourseMeta {
  return {
    id: course.id,
    slug: course.slug,
    title: course.title,
    shortTitle: course.shortTitle,
    description: course.description,
    technology: course.technology,
    category: course.category,
    type: course.type,
    difficulty: course.difficulty,
    badges: course.badges,
    topics: course.topics,
    icon: course.icon,
    projects: course.projects.map((project) => project.slug),
    sections: course.sections.map((section) => ({
      id: section.id,
      title: section.title,
      description: section.description,
      lessons: section.lessons.map((lesson) => ({
        id: lesson.id,
        title: lesson.title,
        description: lesson.description,
        duration: lesson.duration,
        objectives: lesson.objectives,
        xp: lesson.xp,
        exerciseCount: lesson.content.filter((block) => block.type === 'exercise').length,
      })),
      quiz: section.quiz,
    })),
  }
}

const courseMeta: CourseMeta[] = [
  htmlFundamentals,
  cssFundamentals,
  javascriptFundamentals,
  domBrowserApisCourse,
  responsiveWebDesignCourse,
  gitGitHubCourse,
  typescriptFundamentals,
  reactCourse,
  frontendProjectsCourse,
].map(toMeta)

const output = `// Generated by scripts/generate-course-meta.ts — edit the course modules and
// run \`npm run generate:course-meta\` instead of editing this file.
import type { CourseMeta } from '~/types/content'

export const courseMeta: CourseMeta[] = ${JSON.stringify(courseMeta, null, 2)}
`

writeFileSync(new URL('../app/content/courses/meta.ts', import.meta.url), output)
console.log(`Wrote course meta for ${courseMeta.length} courses`)
