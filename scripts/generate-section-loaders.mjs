import { execFileSync } from 'node:child_process'
import { mkdirSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { build } from 'esbuild'

/**
 * Builds the runtime section loader map.
 *
 * Lesson pages only need one section's body. The course modules still assemble
 * every section for the metadata generator and the content tests, but they are
 * never imported by the client. Each section file is therefore a dynamic import
 * of its own, and opening one lesson downloads one section rather than a whole
 * course.
 */

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const coursesRoot = join(root, 'app', 'content', 'courses')
const directories = ['html', 'css', 'js', 'ts', 'react', 'frontend-projects']
const monoliths = ['dom-browser-apis.ts', 'responsive-web-design.ts', 'git-github.ts']

const files = []
for (const directory of directories) {
  for (const name of readdirSync(join(coursesRoot, directory)).sort()) {
    if (name.endsWith('.ts')) files.push(`${directory}/${name}`)
  }
}
files.push(...monoliths)

const imports = files
  .map((file, index) => `import * as m${index} from './app/content/courses/${file}'`)
  .join('\n')
const modules = files
  .map((file, index) => `  ${JSON.stringify(file)}: m${index},`)
  .join('\n')

const scanSource = `${imports}

const modules = {
${modules}
}

const result = {}
for (const [file, module] of Object.entries(modules)) {
  const ids = []
  for (const value of Object.values(module)) {
    if (Array.isArray(value)) {
      for (const section of value) {
        if (section && typeof section === 'object' && typeof section.id === 'string') {
          ids.push(section.id)
        }
      }
    } else if (value && typeof value === 'object' && typeof value.id === 'string') {
      ids.push(value.id)
    }
  }
  result[file] = ids
}
console.log(JSON.stringify(result))
`

const scan = await build({
  stdin: {
    contents: scanSource,
    resolveDir: root,
    sourcefile: 'section-scan.ts',
    loader: 'ts',
  },
  alias: { '~': join(root, 'app') },
  bundle: true,
  platform: 'node',
  format: 'esm',
  write: false,
  logLevel: 'silent',
})

mkdirSync(join(root, '.tmp'), { recursive: true })
const scanFile = join(root, '.tmp', 'section-scan.mjs')
writeFileSync(scanFile, scan.outputFiles[0].text)
const output = execFileSync(process.execPath, [scanFile], {
  cwd: root,
  encoding: 'utf8',
})
const scanned = JSON.parse(output)

const sectionModule = {}
for (const file of files) {
  for (const id of scanned[file]) {
    if (sectionModule[id] && sectionModule[id] !== file) {
      throw new Error(`Section ${id} is exported by both ${sectionModule[id]} and ${file}`)
    }
    sectionModule[id] = file
  }
}

const loaderEntries = files
  .map((file) => `  ${JSON.stringify(file)}: () => import(${JSON.stringify(`./${file.replace(/\.ts$/, '')}`)}),`)
  .join('\n')
const idEntries = Object.entries(sectionModule)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([id, file]) => `  ${JSON.stringify(id)}: ${JSON.stringify(file)},`)
  .join('\n')
const ids = Object.keys(sectionModule).sort()

const source = `// Generated by scripts/generate-section-loaders.mjs. Do not edit by hand.
import type { Section } from '~/types/content'

type SectionModule = Record<string, unknown>

/**
 * Each key is a section file, imported only when a lesson or quiz from that file
 * is opened. A file may export more than one section array; the lookup below
 * checks every exported array for the requested id.
 */
const sectionModules: Record<string, () => Promise<SectionModule>> = {
${loaderEntries}
}

const sectionFile: Record<string, string> = {
${idEntries}
}

/** Every section id with a loader, so the content tests can prove none is missing. */
export const sectionLoaderIds: string[] = ${JSON.stringify(ids)}

export async function loadSection(sectionId: string): Promise<Section | undefined> {
  const file = sectionFile[sectionId]
  if (!file) return undefined
  const loader = sectionModules[file]
  if (!loader) return undefined
  const module = await loader()
  for (const value of Object.values(module)) {
    if (Array.isArray(value)) {
      const found = value.find(
        (entry): entry is Section =>
          Boolean(entry) && typeof entry === 'object' && (entry as Section).id === sectionId,
      )
      if (found) return found
    } else if (
      value &&
      typeof value === 'object' &&
      (value as Section).id === sectionId
    ) {
      return value as Section
    }
  }
  return undefined
}
`

writeFileSync(join(coursesRoot, 'section-loaders.ts'), source)
console.log(`Wrote ${ids.length} section loaders across ${files.length} modules`)
